"""Export the MCP tool catalog from the live tool registry.

Two renderings of the same source (`mcp.list_tools()` — the registry that
also feeds `describe` and the runtime /llms.txt):

  markdown (default) — the docs-site reference page. CI regenerates and
    fails on drift, so the page can never fall out of sync with the server:
      uv run python scripts/export_mcp_catalog.py > docs/src/content/docs/reference/mcp-tools.md

  --format json — the tool-schema snapshot pinned by
    tests/test_mcp.py::test_tool_schemas_unchanged_by_audit_wrapper:
      uv run python scripts/export_mcp_catalog.py --format json \
        > tests/fixtures/mcp_tools_snapshot.json
"""

import argparse
import asyncio
import json
import os
import sys
from typing import Any

from cryptography.fernet import Fernet

# create_app/server import requires an encryption key at import time (issue
# #93); listing tool schemas never touches encrypted data, so a throwaway key
# is fine (same trick as export_openapi.py).
os.environ.setdefault("PURSER_ENCRYPTION_KEY", Fernet.generate_key().decode())

from purser.mcp.server import mcp

# NOTE: no raw HTML comments in the emitted markdown — starlight-md-txt runs
# every page through an MDX-aware parser where `<!-- -->` is a syntax error.
# The do-not-edit marker is a YAML comment in the frontmatter plus a visible
# provenance line in the body.
HEADER = """\
---
# GENERATED by scripts/export_mcp_catalog.py — do not edit by hand.
# Tool behavior and wording live in the docstrings in purser/mcp/server.py.
# Regenerate: uv run python scripts/export_mcp_catalog.py \
#   > docs/src/content/docs/reference/mcp-tools.md
title: MCP tools
description: Every tool Purser's MCP server exposes, generated from the live tool registry.
---

_Generated from the live tool registry by `scripts/export_mcp_catalog.py`;
tool descriptions are the server docstrings verbatim._

Connect any MCP client to `https://<purser-host>/mcp` (streamable HTTP) with
`Authorization: Bearer <api-token>` — see [Connect an agent](../../how-to/connect-an-agent/).
Recommended agent scopes: `read + write`. Call `describe` first in every
fresh session; a running instance also serves this guide at `GET /llms.txt`.
"""


def _dump_tools() -> list[dict[str, Any]]:
    async def dump() -> list[dict[str, Any]]:
        tools = await mcp.list_tools()
        return sorted(
            (
                {"name": t.name, "description": t.description, "inputSchema": t.parameters}
                for t in tools
            ),
            key=lambda t: t["name"],
        )

    return asyncio.run(dump())


def _render_type(prop: dict[str, Any]) -> str:
    # \| — these land in markdown table cells, where a bare pipe splits the row.
    if "anyOf" in prop:
        return " \\| ".join(_render_type(sub) for sub in prop["anyOf"])
    type_ = prop.get("type")
    if type_ == "array" and isinstance(prop.get("items"), dict):
        return f"array of {_render_type(prop['items'])}"
    if isinstance(type_, str):
        return type_
    # No plain type (bare enum/const/ref) — compact JSON of the shape.
    shape = {k: v for k, v in prop.items() if k not in ("title", "default", "description")}
    return f"`{json.dumps(shape, sort_keys=True, separators=(',', ':'))}`"


def _render_markdown(tools: list[dict[str, Any]]) -> str:
    lines = [HEADER]
    for tool in tools:
        lines.append(f"## {tool['name']}")
        lines.append("")
        description = (tool["description"] or "").strip()
        if description:
            lines.append(description)
            lines.append("")
        schema = tool["inputSchema"] or {}
        properties: dict[str, Any] = schema.get("properties") or {}
        if properties:
            required = set(schema.get("required") or ())
            lines.append("| Parameter | Type | Required | Default |")
            lines.append("| --- | --- | --- | --- |")
            for name, prop in properties.items():  # signature order — deterministic
                type_str = _render_type(prop)
                req = "yes" if name in required else "no"
                default = f"`{json.dumps(prop['default'])}`" if "default" in prop else "—"
                lines.append(f"| `{name}` | {type_str} | {req} | {default} |")
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--format", choices=("markdown", "json"), default="markdown")
    args = parser.parse_args()

    tools = _dump_tools()
    if args.format == "json":
        json.dump(tools, sys.stdout, indent=2)
        sys.stdout.write("\n")
    else:
        sys.stdout.write(_render_markdown(tools))


if __name__ == "__main__":
    main()
